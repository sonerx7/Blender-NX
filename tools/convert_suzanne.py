import sys
import os

def parse_and_convert_suzanne(obj_path, out_header):
    vertices = []
    faces = []

    with open(obj_path, 'r') as f:
        for line in f:
            line = line.strip()
            if not line or line.startswith('#'):
                continue
            parts = line.split()
            if parts[0] == 'v':
                x, y, z = float(parts[1]), float(parts[2]), float(parts[3])
                vertices.append((x, y, z))
            elif parts[0] == 'f':
                # faces can be v, v/vt, v//vn, v/vt/vn
                idx = [int(p.split('/')[0]) - 1 for p in parts[1:]]
                if len(idx) == 3:
                    faces.append((idx[0], idx[1], idx[2]))
                elif len(idx) == 4:
                    # triangulate quad
                    faces.append((idx[0], idx[1], idx[2]))
                    faces.append((idx[0], idx[2], idx[3]))

    # Center and scale vertices
    min_x = min(v[0] for v in vertices)
    max_x = max(v[0] for v in vertices)
    min_y = min(v[1] for v in vertices)
    max_y = max(v[1] for v in vertices)
    min_z = min(v[2] for v in vertices)
    max_z = max(v[2] for v in vertices)

    cx = (min_x + max_x) * 0.5
    cy = (min_y + max_y) * 0.5
    cz = (min_z + max_z) * 0.5

    max_extent = max(max_x - min_x, max_y - min_y, max_z - min_z)
    scale = 2.0 / max_extent

    norm_verts = []
    for v in vertices:
        nx = (v[0] - cx) * scale
        ny = (v[1] - cy) * scale
        nz = (v[2] - cz) * scale
        norm_verts.append((nx, ny, nz))

    # Compute normals per vertex
    normals = [[0.0, 0.0, 0.0] for _ in norm_verts]
    for f in faces:
        v0 = norm_verts[f[0]]
        v1 = norm_verts[f[1]]
        v2 = norm_verts[f[2]]
        # edge vectors
        e1 = (v1[0] - v0[0], v1[1] - v0[1], v1[2] - v0[2])
        e2 = (v2[0] - v0[0], v2[1] - v0[1], v2[2] - v0[2])
        # cross product
        fnx = e1[1]*e2[2] - e1[2]*e2[1]
        fny = e1[2]*e2[0] - e1[0]*e2[2]
        fnz = e1[0]*e2[1] - e1[1]*e2[0]
        for vid in f:
            normals[vid][0] += fnx
            normals[vid][1] += fny
            normals[vid][2] += fnz

    # Normalize normals
    import math
    for i in range(len(normals)):
        n = normals[i]
        l = math.sqrt(n[0]*n[0] + n[1]*n[1] + n[2]*n[2])
        if l > 1e-6:
            normals[i] = [n[0]/l, n[1]/l, n[2]/l]
        else:
            normals[i] = [0.0, 1.0, 0.0]

    with open(out_header, 'w', encoding='utf-8') as out:
        out.write("#pragma once\n// Autogenerated Suzanne Monkey Mesh for Blender NX\n\n")
        out.write(f"static const int kSuzanneVertexCount = {len(norm_verts)};\n")
        out.write(f"static const int kSuzanneTriangleCount = {len(faces)};\n\n")

        out.write("static const float kSuzanneVertices[][3] = {\n")
        for v in norm_verts:
            out.write(f"    {{{v[0]:.6f}f, {v[1]:.6f}f, {v[2]:.6f}f}},\n")
        out.write("};\n\n")

        out.write("static const float kSuzanneNormals[][3] = {\n")
        for n in normals:
            out.write(f"    {{{n[0]:.6f}f, {n[1]:.6f}f, {n[2]:.6f}f}},\n")
        out.write("};\n\n")

        out.write("static const unsigned short kSuzanneIndices[][3] = {\n")
        for f in faces:
            out.write(f"    {{{f[0]}, {f[1]}, {f[2]}}},\n")
        out.write("};\n")

    print(f"Generated {out_header}: {len(norm_verts)} verts, {len(faces)} triangles.")

if __name__ == '__main__':
    parse_and_convert_suzanne('nexvyn-blender/src/suzanne.obj', 'nexvyn-blender/src/Suzanne.h')
